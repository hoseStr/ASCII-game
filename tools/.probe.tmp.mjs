import { chromium } from 'playwright';
import { createServer } from 'vite';
const server = await createServer({ root: process.cwd(), server: { port: 5197, strictPort: true }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ channel: 'msedge', args: ['--ignore-gpu-blocklist', '--enable-gpu', '--use-angle=d3d11'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
const t0 = Date.now();
await page.goto('http://localhost:5197/');
await page.waitForFunction(() => document.body.dataset.ready === '1', null, { timeout: 60000 });
console.log('ready after', Date.now() - t0, 'ms');
await page.waitForTimeout(1500);
const s = await page.evaluate(() => window.__adg.stats());
console.log('boot', s.bootMs.toFixed(0), 'ms; compile:', s.compile.join(' · '));
await browser.close();
await server.close();
